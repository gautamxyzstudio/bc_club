"""Turn the designer's listing-details.html into the site's listing page engine.

    python scripts/bclisting/build_listing_engine.py path/to/listing-details.html

Writes
  src/mainComponents/bcListing/bcListing.css        the page styles (all inside .bcl), sticky parts sit under the site header
  src/mainComponents/bcListing/bcListingEngine.js   mountBCListing(host, config) -> { render, refresh, destroy }

The design's own code runs unchanged except for the few rules below (each must match once, or the script stops and
prints the line it could not find, so a new version from the designer is easy to re-apply).
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "mainComponents", "bcListing")


def once(s, old, new):
    n = s.count(old)
    if n != 1:
        raise SystemExit(f"STOP: expected once, found {n}:\n{old[:160]}")
    return s.replace(old, new)


def main(path):
    html = open(path, encoding="utf-8").read()
    os.makedirs(OUT, exist_ok=True)

    # ---------------------------------------------------------------- styles
    css = re.search(r"<style>\s*(/\* ######## PART 1: STYLES.*?)</style>", html, re.S).group(1)
    css = once(css, ".bcl-sec { background: #fff;", ".bcl-sec { scroll-margin-top: calc(var(--bcl-sticky-top, 0px) + 64px) !important; background: #fff;")
    css = once(css, ".bcl-tabs { position: sticky; top: 0;", ".bcl-tabs { position: sticky; top: var(--bcl-sticky-top, 0px);")
    css = once(css, ".bcl-side { position: sticky; top: 16px; }", ".bcl-side { position: sticky; top: calc(var(--bcl-sticky-top, 0px) + 16px); }")
    css = once(css, "font-family: var(--bcl-font); color: var(--bcl-text); font-size: 14.5px;", "font-family: var(--bcl-font); color: var(--bcl-text); font-size: 14.5px; background: #f8fafc;")
    css += ("\n/* site: galleries with fewer than 5 photos */\n@media (min-width: 720px) {\n"
            "  .bcl-gal.n1 { grid-template-columns: 1fr; height: 460px; } .bcl-gal.n1 .bcl-g0 { grid-row: auto; }\n"
            "  .bcl-gal.n2 { grid-template-columns: 2fr 1fr; } .bcl-gal.n2 .bcl-gs { grid-row: span 2; }\n"
            "  .bcl-gal.n3 { grid-template-columns: 2fr 1fr; }\n"
            "  .bcl-gal.n4 { grid-template-columns: 2fr 1fr 1fr; } .bcl-gal.n4 .bcl-gs:nth-child(2) { grid-row: span 2; }\n}\n")
    css += "\n/* site: the page's chat bubble and bottom bar stay clear of each other on phones */\n.bcl-bar2 { z-index: 45; }\n.bcl-loading { color: var(--bcl-muted); font-size: 13px; }\n"
    open(os.path.join(OUT, "bcListing.css"), "w", encoding="utf-8").write("/* Listing details page styles (designer version Nov 13 F). Everything is inside .bcl. Generated by scripts/bclisting/build_listing_engine.py */\n" + css)

    # ---------------------------------------------------------------- markup (without the demo switcher)
    body = re.search(r'(<div class="bcl" id="bcl">.*?</div>\n)\s*<script>', html, re.S).group(1)
    body = re.sub(r"\s*<!-- ===== DEMO START \(D2\).*?<!-- ===== DEMO END \(D2\) ===== -->", "", body, flags=re.S)

    # ---------------------------------------------------------------- code
    js = re.search(r"<script>\n(window\.BCL_NOPHOTO = .*?)\n\(\(\) => \{\n(.*)\n\}\)\(\);\n</script>", html, re.S)
    nophoto, code = js.group(1), js.group(2)
    code = once(code, "const CFG = window.BCListingConfig || {}, DEMO = CFG.demo !== false;", "const DEMO = CFG.demo !== false;")
    # one instance per page: listeners are removed again by destroy()
    for ev in ("click", "submit", "keydown"):
        code = once(code, f'document.addEventListener("{ev}", e => {{', f'on(document, "{ev}", e => {{')
    # the site decides whether the heart starts filled; refresh() keeps calculator inputs and the heart
    code = once(code, "function render(l) { L = l; MC.down = null; saved = false;",
                "function render(l, keep) { L = l; if (!keep) { MC.down = null; saved = typeof CFG.isSaved === \"function\" ? !!CFG.isSaved(l) : false; }")
    # tabs follow the scroll without moving the page
    code = once(code, 'if (on) t.scrollIntoView({ block: "nearest", inline: "nearest" });',
                "if (on && t.parentElement) { const nav = t.parentElement; nav.scrollLeft = t.offsetLeft - nav.clientWidth / 2 + t.offsetWidth / 2; }")
    # links to other homes and to the map: let the site route them (no full reload)
    code = once(code, '    const a = b.dataset.act; if (!a) return;',
                '    const a = b.dataset.act; if (!a) return;')
    code = once(code, 'const b = e.target.closest("[data-act], .bcl-seg button, .bcl-days button, [data-demo]"); if (!b || !b.closest(".bcl")) return;',
                'const ln = e.target.closest(".bcl a[href^=\'/\']"); if (ln && typeof CFG.onNavigate === "function" && !e.metaKey && !e.ctrlKey && !e.shiftKey && e.button === 0) { e.preventDefault(); CFG.onNavigate(ln.getAttribute("href")); return; }\n'
                '    const b = e.target.closest("[data-act], .bcl-seg button, .bcl-days button, [data-demo]"); if (!b || !b.closest(".bcl")) return;')
    code = once(code, "  window.BCListing = { render, _calc: { pay, ptt, minDown, cmhcPct } };\n  render(CFG.listing || (DEMO ? SAMPLES.condo : null) || { address: \"Listing not found\", photos: [] });",
                "  if (CFG.listing || DEMO) render(CFG.listing || SAMPLES.condo);\n"
                "  return { render: l => render(l), refresh: l => { const y = window.scrollY; render(l || L, true); window.scrollTo(0, y); }, get listing() { return L; },\n"
                "    destroy: () => { offs.forEach(f => f()); if (spyObs) spyObs.disconnect(); clearTimeout(toast.t); document.body.style.overflow = \"\"; const ld = document.getElementById(\"bclLd\"); if (ld) ld.remove(); host.innerHTML = \"\"; } };")

    # schools: say so when it is the closest public school, not the catchment one
    code = once(code, '<small>${lab} catchment${o.grades ? " · " + esc(o.grades) : ""}</small>',
                '<small>${lab}${o.inCatch === false ? " · closest public school" : o.shared ? " · shared catchment" : " catchment"}${o.grades ? " · " + esc(o.grades) : ""}</small>')
    # assessment: link to our full assessment page when we have it
    code = once(code, '<p class="bcl-note">The assessed value is set every July for the next year and is not an appraisal. Homes often sell above or below it.</p>',
                '${a.url ? `<a class="bcl-btn" style="margin-top:12px;width:100%" href="${esc(a.url)}">View full assessment</a>` : ""}<p class="bcl-note">The assessed value is set every July for the next year and is not an appraisal. Homes often sell above or below it.</p>')

    # the site can refuse a save (not signed in): the heart goes back
    code = once(code, 'if (typeof CFG.onSave === "function") CFG.onSave(L, saved); toast(saved ? "Saved to your homes" : "Removed from saved");',
                'if (typeof CFG.onSave === "function" && CFG.onSave(L, saved) === false) { saved = !saved; b.classList.toggle("on", saved); b.setAttribute("aria-pressed", saved); return; } toast(saved ? "Saved to your homes" : "Removed from saved");')

    # fewer than 5 photos: the gallery grid fits what there is (no empty boxes)
    code = once(code, 'return `<div class="bcl-gal">${img(ph[0], 0, "bcl-g0")}', 'return `<div class="bcl-gal n${Math.min(ph.length, 5)}">${img(ph[0], 0, "bcl-g0")}')

    engine = (
        "// @ts-nocheck\n/* eslint-disable */\n"
        "/**\n * Listing details page engine (designer version Nov 13 F), generated by scripts/bclisting/build_listing_engine.py.\n"
        " * mountBCListing(host, config) draws the page into `host` and returns { render(listing), refresh(listing?), destroy() }.\n"
        " * config: { demo:false, listing, theme, agent, partners, signedIn, historyNeedsSignIn, isSaved(l), onSave(l, saved),\n"
        " *   onBookShowing(lead), onQuestion(lead), onPartnerLead(lead), onPhotos(l), onSignIn(), mapUrl(l), onNavigate(href) }\n"
        " * (c) BC Real Estate Market. All rights reserved.\n */\n"
        f"const MARKUP = {json.dumps(body.strip())};\n\n"
        "export function mountBCListing(host, CFG = {}) {\n"
        "  host.innerHTML = MARKUP;\n"
        f"  {nophoto}\n"
        "  const offs = [], on = (t, ev, fn) => { t.addEventListener(ev, fn); offs.push(() => t.removeEventListener(ev, fn)); };\n"
        + code + "\n}\n"
    )
    open(os.path.join(OUT, "bcListingEngine.js"), "w", encoding="utf-8").write(engine)
    print("bcListing.css + bcListingEngine.js written to", OUT)


if __name__ == "__main__":
    main(sys.argv[1])
